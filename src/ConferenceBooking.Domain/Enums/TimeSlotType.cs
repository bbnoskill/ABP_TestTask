namespace ConferenceBooking.Domain.Enums
{
    /// <summary>
    /// Визначає тип часового слоту для розрахунку вартості оренди.
    /// Кожен тип має свій коефіцієнт, що впливає на базову ставку.
    /// </summary>
    public enum TimeSlotType
    {
        /// <summary>
        /// Стандартні години (09:00–18:00). Коефіцієнт: 1.0 (базова вартість).
        /// </summary>
        Standard,

        /// <summary>
        /// Вечірні години (18:00–23:00). Знижка 20%, коефіцієнт: 0.8.
        /// </summary>
        Evening,

        /// <summary>
        /// Ранкові години (06:00–09:00). Знижка 10%, коефіцієнт: 0.9.
        /// </summary>
        Morning,

        /// <summary>
        /// Пікові години (12:00–14:00). Націнка 15%, коефіцієнт: 1.15.
        /// </summary>
        Peak
    }
}
